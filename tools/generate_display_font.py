#!/usr/bin/env python3
"""Generate the redistributable onboard screen atlas; no runtime font dependency."""
import argparse
import hashlib
from pathlib import Path
from PIL import Image, ImageDraw, ImageFont

parser = argparse.ArgumentParser()
parser.add_argument("--font", default="/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")
parser.add_argument("--check", action="store_true", help="Verify the committed header without rewriting it")
args = parser.parse_args()
source = Path(args.font)
font = ImageFont.truetype(str(source), 28)
atlas = Image.new("L", (512, 256), 0)
draw = ImageDraw.Draw(atlas)
metrics = []
for code in range(32, 127):
    index = code - 32
    x, y = (index % 16) * 32 + 2, (index // 16) * 40 + 30
    glyph = chr(code)
    left, top, right, bottom = font.getbbox(glyph, anchor="ls")
    assert 0 <= 2 + left <= 2 + right <= 32
    assert 0 <= 30 + top <= 30 + bottom <= 40
    draw.text((x, y), glyph, font=font, fill=255, anchor="ls")
    metrics.append((x+left, y+top, right-left, bottom-top, left, top,
                    round(font.getlength(glyph)*64)))

# Lossless run-length encoding of antialiased coverage, not colour images.
runs = []
previous, count = None, 0
for value in atlas.tobytes():
    if value == previous and count < 255:
        count += 1
    else:
        if count:
            runs.append((count << 8) | previous)
        previous, count = value, 1
runs.append((count << 8) | previous)
root = Path(__file__).resolve().parent.parent
target = root / "include/trainsim/render/DisplayFontData.hpp"
lines = ["// Generated by tools/generate_display_font.py. Do not edit manually.",
         "// DejaVu Sans 2.37 raster subset; see assets/licenses/DejaVu.txt.",
         f"// Source SHA-256: {hashlib.sha256(source.read_bytes()).hexdigest()}",
         "#pragma once", "#include <array>", "#include <cstdint>",
         "namespace TrainSim::Render::DisplayFontData {",
         "struct Glyph { int x,y,width,height,left,top,advance64; };",
         "inline constexpr std::array<Glyph,95> Glyphs={{"]
lines += ["    {"+",".join(map(str, values))+"}," for values in metrics]
lines += ["}};", f"inline constexpr std::array<std::uint16_t,{len(runs)}> CoverageRuns={{"]
lines += ["    "+",".join(map(str,runs[i:i+20]))+"," for i in range(0,len(runs),20)]
lines += ["};", "} // namespace TrainSim::Render::DisplayFontData", ""]
output = "\n".join(lines)
if args.check:
    if target.read_text(encoding="ascii") != output:
        raise SystemExit("Committed passenger display font differs from deterministic generation")
else:
    target.write_text(output, encoding="ascii")
action = "Verified" if args.check else "Generated"
print(f"{action} {target.relative_to(root)}: {len(runs)} coverage runs, {target.stat().st_size} bytes")
