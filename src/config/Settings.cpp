std::string trim(std::string value)
{
    const auto visible = [](unsigned char character) { return !std::isspace(character); };
    value.erase(value.begin(), std::find_if(value.begin(), value.end(), visible));
    value.erase(std::find_if(value.rbegin(), value.rend(), visible).base(), value.end());
    return value;
}

float parseNumber(const std::string& text, std::size_t line)
{
    std::size_t used = 0;
    try
    {
        const float value = std::stof(text, &used);
        if (used != text.size() || !std::isfinite(value))
            throw std::invalid_argument("non-finite or trailing characters");
        return value;
    }
    catch (const std::exception&)
    {
        throw std::runtime_error("Invalid numeric setting on line " + std::to_string(line));
    }
}

