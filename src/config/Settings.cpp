Settings Settings::parse(std::string_view text)
{
    return parse(text, Settings{});
}

Settings Settings::parse(std::string_view text, Settings settings)
{
    std::istringstream input{std::string(text)};
    std::string line;
    std::size_t lineNumber = 0;
    while (std::getline(input, line))
    {
        ++lineNumber;
        const auto comment = line.find('#');
        if (comment != std::string::npos) line.erase(comment);
        line = trim(std::move(line));
        if (line.empty()) continue;
        const auto separator = line.find('=');
        if (separator == std::string::npos)
            throw std::runtime_error("Expected key=value on settings line " + std::to_string(lineNumber));
        const std::string key = trim(line.substr(0, separator));
        const float value = parseNumber(trim(line.substr(separator + 1)), lineNumber);

        if (key == "mouse_sensitivity") settings.mouseSensitivity = std::clamp(value, 0.0005f, 0.010f);
        else if (key == "master_volume") settings.masterVolume = std::clamp(value, 0.0f, 1.0f);
        else if (key == "announcement_volume") settings.announcementVolume = std::clamp(value, 0.0f, 1.0f);
        else if (key == "passenger_volume") settings.passengerVolume = std::clamp(value, 0.0f, 1.0f);
        else if (key == "train_volume") settings.trainVolume = std::clamp(value, 0.0f, 1.0f);
        else if (key == "camera_vibration") settings.cameraVibration = std::clamp(value, 0.0f, 1.0f);
        else if (key == "field_of_view_degrees") settings.fieldOfViewDegrees = std::clamp(value, 55.0f, 100.0f);
        else if (key == "graphics_quality")
            settings.graphicsQuality = std::clamp(static_cast<int>(std::lround(value)), 0, 2);
        else if (key == "vegetation_distance_metres")
            settings.vegetationDistanceMetres = std::clamp(value, 250.0f, 1'000.0f);
        else if (key == "announcement_captions") settings.announcementCaptions = value >= 0.5f;
        else if (key == "service_start_minutes")
            settings.serviceStartMinutes = std::clamp(static_cast<int>(std::lround(value)), 0, 1'439);
        else if (key == "weather")
            settings.weatherMode = std::clamp(static_cast<int>(std::lround(value)), 0, 5);
        else throw std::runtime_error("Unknown setting '" + key + "' on line "
                                      + std::to_string(lineNumber));
    }
    return settings;
}

Settings Settings::load(const std::filesystem::path& path)
{
    return load(path, Settings{});
}

Settings Settings::load(const std::filesystem::path& path, Settings base)
{
    std::ifstream input(path);
    if (!input) return base;
    std::ostringstream contents;
    contents << input.rdbuf();
    return parse(contents.str(), base);
}

std::string Settings::serialize() const
{
    std::ostringstream output;
    output << "# User preferences generated by Train Simulator.\n"
           << std::fixed << std::setprecision(4)
           << "mouse_sensitivity = " << mouseSensitivity << '\n'
           << "master_volume = " << masterVolume << '\n'
           << "announcement_volume = " << announcementVolume << '\n'
           << "passenger_volume = " << passengerVolume << '\n'
           << "train_volume = " << trainVolume << '\n'
           << "camera_vibration = " << cameraVibration << '\n'
           << "field_of_view_degrees = " << fieldOfViewDegrees << '\n'
           << "graphics_quality = " << graphicsQuality << '\n'
           << "vegetation_distance_metres = " << vegetationDistanceMetres << '\n'
           << "announcement_captions = " << (announcementCaptions ? 1 : 0) << '\n'
           << "service_start_minutes = " << serviceStartMinutes << '\n'
           << "weather = " << weatherMode << '\n';
    return output.str();
}

void Settings::save(const std::filesystem::path& path) const
{
    if (!path.parent_path().empty()) std::filesystem::create_directories(path.parent_path());
    std::filesystem::path temporary = path;
    temporary += ".tmp";
    {
        std::ofstream output(temporary, std::ios::trunc);
        if (!output)
            throw std::runtime_error("Could not open settings file for writing: " + temporary.string());
        output << serialize();
        if (!output)
        {
            output.close();
            std::filesystem::remove(temporary);
            throw std::runtime_error("Could not write settings file: " + temporary.string());
        }
    }
    std::error_code error;
    std::filesystem::rename(temporary, path, error);
    if (error)
    {
        std::filesystem::remove(temporary);
        throw std::runtime_error("Could not replace settings file: " + path.string()
                                 + ": " + error.message());
    }
}

Settings settingsForPersistence(Settings runtime, int loadedGraphicsQuality,
                                bool launchQualityOverride,
                                bool graphicsQualityAdjustedInMenu) noexcept
{
    if (launchQualityOverride && !graphicsQualityAdjustedInMenu)
        runtime.graphicsQuality = std::clamp(loadedGraphicsQuality,0,2);
    return runtime;
}

